import json
import subprocess
from pathlib import Path
from datetime import datetime
import torch
from .metrics import MetricCalculator
from .validator import SchemaValidator

class ExperimentLogger:
    def __init__(self, experiment_id, method_name, method_key, family, subfamily):
        self.data = {
            "experiment_id": experiment_id,
            "method_name": method_name,
            "method_key": method_key,
            "family": family,
            "subfamily": subfamily,
            "code_version": self._get_git_hash(),
            "seed": 42,
            "timestamp": datetime.now().isoformat(),
            # 初始化空结构以防后续忘记 set
            "task": {},
            "preprocessing": {},
            "model": {"family": family, "details": {}},
            "training": {},
            "hardware": {},
            "results": {}
        }

    def _get_git_hash(self):
        try:
            return subprocess.check_output(['git', 'rev-parse', '--short', 'HEAD']).decode().strip()
        except:
            return "unknown"

    def set_task(self, dataset="alex", label_space="alex-102", grid="mprage", split_id="fold1", train_sub=[], test_sub=[]):
        self.data["task"] = {
            "dataset": dataset,
            "label_space": label_space,
            "grid": grid,
            "split": {
                "scheme": "subject-wise",
                "split_id": split_id,
                "train_subjects": train_sub,
                "test_subjects": test_sub
            },
            "n_voxels": {} # 用户需手动更新或传入
        }

    def set_preprocessing(self, norm_type="global_standard_scaler", feature_version="voxel_signature_v1", **kwargs):
        self.data["preprocessing"] = {
            "feature_version": feature_version,
            "normalisation": {"type": norm_type, "params": kwargs},
            "background_handling": "drop_ignore_index",
            "class_weighting": {"scheme": "none"} # 默认
        }

    def set_model_details(self, param_count_m, **details):
        """
        设置模型细节，kwargs 会自动放入 model.details
        例如: logger.set_model_details(52.0, input_dim=341, hidden_layers=[4096]*4)
        """
        self.data["model"]["param_count_m"] = param_count_m
        self.data["model"]["details"] = details

    def set_training_config(self, batch_size, epochs, lr, optimizer="adam", **kwargs):
        self.data["training"] = {
            "batch_size": batch_size,
            "n_epochs": epochs,
            "optimizer": {"type": optimizer, "lr": lr},
            "loss": {"type": "cross_entropy"},
            **kwargs
        }

    def set_hardware(self, train_time_hours=None):
        self.data["hardware"] = {
            "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else "cpu",
            "num_gpus": torch.cuda.device_count(),
            "train_time_hours": train_time_hours
        }

    def log_results(self, y_true, y_pred_proba, loss_val=None, split="test", additional_metrics=None):
        """
        自动计算并记录结果
        """
        # 1. 自动计算通用指标
        metrics = MetricCalculator.compute_all(y_true, y_pred_proba, loss_val)
        
        # 2. 合并用户自定义指标 (如果有)
        if additional_metrics:
            metrics.update(additional_metrics)

        self.data["results"] = {
            "evaluated_split": split,
            "global_metrics": metrics,
            "logs": {},
            "notes": f"Auto-generated by ExperimentLogger on {datetime.now().date()}"
        }

    def save(self, output_dir, validate=True):
        """保存 JSON 并进行 Schema 验证"""
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
        path = output_dir / f"{self.data['experiment_id']}.json"

        # 验证
        if validate:
            is_valid, errors = SchemaValidator.validate(self.data)
            if not is_valid:
                print(f"\n⚠️  SCHEMA VALIDATION FAILED for {self.data['experiment_id']}:")
                for err in errors:
                    print(f"  - {err}")
                print("  (File will still be saved for debugging)\n")
            else:
                print(f"✅ Schema validation passed.")

        with open(path, "w", encoding='utf-8') as f:
            json.dump(self.data, f, indent=2)
        print(f"📄 Experiment log saved to: {path}")